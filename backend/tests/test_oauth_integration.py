async def _seed_pending_request(provider: TracynOAuthProvider, *, redirect_uri="https://claude.ai/callback") -> str:
    client_info = OAuthClientInformationFull(client_id="client-1", client_name="Claude", redirect_uris=[redirect_uri])
    params = AuthorizationParams(
        state="xyz", scopes=["mcp"], code_challenge="chal", redirect_uri=redirect_uri, redirect_uri_provided_explicitly=True
    )
    url = await provider.authorize(client_info, params)
    return url.rsplit("=", 1)[1]


