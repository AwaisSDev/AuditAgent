"""Integration tests for the OAuth consent router (routers/oauth.py) --
the human-facing half of the MCP server's login flow, exercised through
the real FastAPI app. The OAuth *protocol* endpoints themselves
(discovery, registration, /authorize, /token) are generated by the mcp
package from TracynOAuthProvider and covered separately in
test_mcp_oauth_provider.py; this file covers what only a real logged-in
dashboard user can do: seeing what's being requested and deciding it,
including that a real, persisted, workspace-scoped API key gets minted
on approval, and that no dashboard user can approve a workspace they
don't belong to."""

import pytest
from fastapi.testclient import TestClient
from mcp.server.auth.provider import AuthorizationParams
from mcp.shared.auth import OAuthClientInformationFull

from app.main import app
from app.security import CurrentUser, get_current_user
from app.services.mcp_oauth_provider import TracynOAuthProvider

USER_ID = "user-1"
WORKSPACE_ID = "ws-1"
OTHER_WORKSPACE_ID = "ws-other"


class _FakeResult:
    def __init__(self, data):
        self.data = data


class _FakeQuery:
    def __init__(self, table, op, payload=None):
        self.table = table
        self.op = op
        self.payload = payload
        self.filters = {}
        self.in_filter = None

    def eq(self, field, value):
        self.filters[field] = value
        return self

    def in_(self, field, values):
        self.in_filter = (field, set(values))
        return self

    def limit(self, _n):
        return self

    def execute(self):
        rows = self.table.rows

        if self.op == "insert":
            row = {"id": f"row-{len(rows) + 1}", **self.payload}
            rows[row["id"]] = row
            return _FakeResult([row])

        matches = [r for r in rows.values() if all(r.get(k) == v for k, v in self.filters.items())]
        if self.in_filter:
            field, values = self.in_filter
            matches = [r for r in matches if r.get(field) in values]
        return _FakeResult(matches)


class _FakeTable:
    def __init__(self, rows):
        self.rows = rows

    def select(self, *_a, **_kw):
        return _FakeQuery(self, "select")

    def insert(self, payload):
        return _FakeQuery(self, "insert", payload)


class _FakeDb:
    def __init__(self):
        self._tables = {
            "workspace_members": {
                "m1": {"workspace_id": WORKSPACE_ID, "user_id": USER_ID},
            },
            "workspaces": {
                WORKSPACE_ID: {"id": WORKSPACE_ID, "name": "Acme Inc"},
                OTHER_WORKSPACE_ID: {"id": OTHER_WORKSPACE_ID, "name": "Someone Else's Workspace"},
            },
            "api_keys": {},
        }

    def table(self, name):
        return _FakeTable(self._tables.setdefault(name, {}))


