def test_get_consent_returns_404_for_an_unknown_request(client):
    resp = client.get("/v1/oauth/consent", params={"request_id": "does-not-exist"})
    assert resp.status_code == 404


@pytest.mark.anyio
async def test_get_consent_shows_the_clients_name_and_the_users_workspaces(client, provider):
    request_id = await _seed_pending_request(provider)

    resp = client.get("/v1/oauth/consent", params={"request_id": request_id})

    assert resp.status_code == 200, resp.text
    body = resp.json()
    assert body["client_name"] == "Claude"
    assert body["workspaces"] == [{"id": WORKSPACE_ID, "name": "Acme Inc"}]
    assert OTHER_WORKSPACE_ID not in [w["id"] for w in body["workspaces"]]


@pytest.mark.anyio
async def test_approving_consent_mints_a_real_api_key_and_redirects_with_a_code(client, provider, fake_db):
    request_id = await _seed_pending_request(provider)

    resp = client.post("/v1/oauth/consent", json={"request_id": request_id, "workspace_id": WORKSPACE_ID})

    assert resp.status_code == 200, resp.text
    redirect_url = resp.json()["redirect_url"]
    assert redirect_url.startswith("https://claude.ai/callback?")
    assert "code=" in redirect_url
    assert "state=xyz" in redirect_url

    # A real, persisted, workspace-scoped API key -- same table, same
    # shape, as one created by hand in Settings.
    created = list(fake_db._tables["api_keys"].values())
    assert len(created) == 1
    assert created[0]["workspace_id"] == WORKSPACE_ID
    assert created[0]["created_by"] == USER_ID
    assert "Claude" in created[0]["name"]


@pytest.mark.anyio
async def test_cannot_approve_consent_for_a_workspace_you_are_not_a_member_of(client, provider, fake_db):
    request_id = await _seed_pending_request(provider)

    resp = client.post("/v1/oauth/consent", json={"request_id": request_id, "workspace_id": OTHER_WORKSPACE_ID})

    assert resp.status_code == 403
    assert fake_db._tables["api_keys"] == {}


@pytest.mark.anyio
async def test_approving_consent_twice_fails_the_second_time(client, provider):
    request_id = await _seed_pending_request(provider)
    client.post("/v1/oauth/consent", json={"request_id": request_id, "workspace_id": WORKSPACE_ID})

    resp = client.post("/v1/oauth/consent", json={"request_id": request_id, "workspace_id": WORKSPACE_ID})

    assert resp.status_code == 404


@pytest.mark.anyio
async def test_denying_consent_redirects_with_access_denied_and_mints_nothing(client, provider, fake_db):
    request_id = await _seed_pending_request(provider)

    resp = client.post("/v1/oauth/deny", json={"request_id": request_id})

    assert resp.status_code == 200, resp.text
    assert "error=access_denied" in resp.json()["redirect_url"]
    assert fake_db._tables["api_keys"] == {}


def test_deny_returns_404_for_an_unknown_request(client):
    resp = client.post("/v1/oauth/deny", json={"request_id": "does-not-exist"})
    assert resp.status_code == 404
